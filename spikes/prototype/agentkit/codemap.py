"""`agentkit codemap`: a compact map of modules, files and public symbols (docs/CODEMAP.md),
so agents navigate by reading one small file instead of exploring the tree."""

from __future__ import annotations

import re
from collections import OrderedDict

from .config import Config
from .util import glob_match, list_repo_files, write_text_lf

HEADER = "# Code map\n\nGenerated by `agentkit codemap`; do not edit. Regenerate after adding files or public symbols.\n"
LINE_CAP = 240


def build(cfg: Config) -> str:
    prof = cfg.profile
    src_globs = prof.get("source_globs") or []
    regexes = [re.compile(r, re.MULTILINE) for r in prof.get("codemap", {}).get("symbol_regexes", [])]
    files = [
        f
        for f in list_repo_files(cfg.root, prof.get("build_output_globs", []))
        if glob_match(f, src_globs) and not f.startswith(".agentkit/")
    ]
    groups: "OrderedDict[str, list[str]]" = OrderedDict()
    for rel in files:
        try:
            text = (cfg.root / rel).read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        symbols: list[str] = []
        for rx in regexes:
            for m in rx.finditer(text):
                name = m.groupdict().get("name") or m.group(m.lastindex or 0)
                if name and name not in symbols:
                    symbols.append(name)
        directory, _, base = rel.rpartition("/")
        entry = f"- {base}" + (": " + ", ".join(symbols) if symbols else "")
        if len(entry) > LINE_CAP:
            entry = entry[: LINE_CAP - 3] + "..."
        groups.setdefault(directory or ".", []).append(entry)
    out = [HEADER]
    for directory, entries in groups.items():
        out.append(f"\n## {directory}\n")
        out.extend(entries)
    return "\n".join(out).rstrip() + "\n"


def write(cfg: Config, check: bool = False) -> bool:
    """Returns True when the file is up to date (check) or was written."""
    target = cfg.root / cfg.path("codemap")
    content = build(cfg)
    current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.is_file() else None
    if check:
        return current == content
    if current != content:
        write_text_lf(target, content)
    return True
